# For loop with else
for i in range(1, 6):
    print("For loop value:", i)   # Print each value
else:
    print("For loop finished successfully")   # Runs when loop ends normally

# While loop with else
count = 1
while count <= 5:
    print("While loop value:", count)   # Print each value
    count += 1
else:
    print("While loop finished successfully")   # Runs when loop ends normally